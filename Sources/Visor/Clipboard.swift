import AppKit
import ImageIO

/// One history entry. Images live in their own file (`clips/<id>.png`) so a new copy only
/// rewrites the small JSON index; the list shows a tiny thumbnail kept inline.
struct Clip: Codable, Identifiable, Equatable {
    var id = UUID()
    var date = Date()
    var text: String?
    var thumb: Data? // ≤160px PNG for the list; set only for image clips
    var isImage: Bool { thumb != nil }
}

/// Polls the pasteboard (there's no change notification on macOS) and keeps the last 40 clips.
/// Skips anything a password manager marks concealed/transient (nspasteboard.org convention).
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()
    @Published var clips: [Clip] = []
    private var lastChange = NSPasteboard.general.changeCount
    private let limit = 40
    private let imageLimit = 10 // images are big; keep only the newest few
    private let io = DispatchQueue(label: "Visor.clipboard.save") // serial: saves land in order
    private let dir: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Visor", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir.appendingPathComponent("clips"), withIntermediateDirectories: true)
        return dir
    }()
    private var file: URL { dir.appendingPathComponent("clipboard.json") }
    private func imageFile(_ id: UUID) -> URL { dir.appendingPathComponent("clips/\(id.uuidString).png") }

    func start() {
        if let data = try? Data(contentsOf: file), let saved = try? JSONDecoder().decode([Clip].self, from: data) {
            // Older versions embedded full images in the JSON; those decode with neither text nor thumb.
            clips = saved.filter { $0.text != nil || $0.isImage }
        }
        removeOrphanImages()
        Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = pb.types ?? []
        let skip = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        if types.contains(where: { skip.contains($0.rawValue) }) { return }

        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(Clip(text: s))
        } else if let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            // PNG encoding a big image takes long enough to stutter the UI: do it on the save queue.
            io.async {
                guard let (png, thumb) = Self.encode(raw), png.count < 8_000_000 else { return }
                let clip = Clip(thumb: thumb)
                try? png.write(to: self.imageFile(clip.id), options: .atomic)
                DispatchQueue.main.async { self.insert(clip) }
            }
        }
    }

    private func insert(_ clip: Clip) {
        if let t = clip.text { clips.removeAll { $0.text == t } }
        clips.insert(clip, at: 0)
        let keptImages = Set(clips.filter(\.isImage).prefix(imageLimit).map(\.id))
        let dropped = clips.enumerated()
            .filter { $0.offset >= limit || ($0.element.isImage && !keptImages.contains($0.element.id)) }
            .map(\.element)
        let droppedIDs = Set(dropped.map(\.id))
        clips.removeAll { droppedIDs.contains($0.id) }
        deleteImages(of: dropped)
        save()
    }

    func copy(_ clip: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let t = clip.text { pb.setString(t, forType: .string) }
        else if let png = try? Data(contentsOf: imageFile(clip.id)) { pb.setData(png, forType: .png) }
        // Let the next poll move it to the top like any fresh copy.
    }

    func delete(_ clip: Clip) { clips.removeAll { $0.id == clip.id }; deleteImages(of: [clip]); save() }
    func clear() { deleteImages(of: clips); clips.removeAll(); save() }

    private func deleteImages(of removed: [Clip]) {
        let files = removed.filter(\.isImage).map { imageFile($0.id) }
        guard !files.isEmpty else { return }
        io.async { files.forEach { try? FileManager.default.removeItem(at: $0) } }
    }

    /// Images left behind by a crash between writing the image and saving the index.
    private func removeOrphanImages() {
        let keep = Set(clips.filter(\.isImage).map { "\($0.id.uuidString).png" })
        let folder = dir.appendingPathComponent("clips")
        io.async {
            for name in (try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? [] where !keep.contains(name) {
                try? FileManager.default.removeItem(at: folder.appendingPathComponent(name))
            }
        }
    }

    /// Off the main thread, and excluded from Time Machine so copied secrets don't live on in backups.
    private func save() {
        let snapshot = clips, file = file, dir = dir
        io.async {
            guard let data = try? JSONEncoder().encode(snapshot) else { return }
            try? data.write(to: file, options: .atomic)
            var url = dir // covers clipboard.json and clips/
            var values = URLResourceValues()
            values.isExcludedFromBackup = true
            try? url.setResourceValues(values)
        }
    }

    /// Pasteboard image data (PNG or TIFF) -> full PNG + small PNG thumbnail.
    static func encode(_ raw: Data) -> (png: Data, thumb: Data)? {
        guard let src = CGImageSourceCreateWithData(raw as CFData, nil),
              let full = CGImageSourceCreateImageAtIndex(src, 0, nil),
              let small = CGImageSourceCreateThumbnailAtIndex(src, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                                                       kCGImageSourceThumbnailMaxPixelSize: 160] as CFDictionary),
              let png = NSBitmapImageRep(cgImage: full).representation(using: .png, properties: [:]),
              let thumb = NSBitmapImageRep(cgImage: small).representation(using: .png, properties: [:]) else { return nil }
        return (png, thumb)
    }
}
